<?php
namespace PurgeKit\Layers;

// Third-party hooks and functions are called here by design.
// phpcs:disable WordPress.NamingConventions.PrefixAllGlobals.NonPrefixedHooknameFound

/**
 * Cache plugins and hosts that expose a plain PHP purge function or action.
 * Names were checked on 2026-11-24 against the plugin sources on wordpress.org
 * (LiteSpeed, W3TC, WP Super Cache, WP Fastest Cache, Nginx Helper, SiteGround) and
 * WP Rocket's docs. WP Engine and Kinsta are closed mu-plugins: community-documented
 * only, so those rows are guarded and fail loudly instead of silently doing nothing.
 */
final class Catalog {
	/** @return CallbackLayer[] */
	public static function callbackLayers(): array {
		return array(
			new CallbackLayer(
				'wp-rocket',
				'WP Rocket',
				Tier::PLUGIN,
				static fn() => function_exists( 'rocket_clean_domain' ),
				static fn() => rocket_clean_domain(),
				static fn( array $urls ) => rocket_clean_files( $urls ),
				Fingerprint::body( '/Debug: cached@\d+/', 'WP Rocket cache' )
			),
			new CallbackLayer(
				'litespeed',
				'LiteSpeed Cache',
				Tier::PLUGIN,
				static fn() => defined( 'LSCWP_V' ),
				static fn() => do_action( 'litespeed_purge_all' ),
				static function ( array $urls ) {
					foreach ( $urls as $url ) {
						do_action( 'litespeed_purge_url', $url );
					}
				},
				Fingerprint::header( 'x-litespeed-cache', '/hit/i', 'LiteSpeed Cache' )
			),
			new CallbackLayer(
				'w3tc',
				'W3 Total Cache',
				Tier::PLUGIN,
				static fn() => function_exists( 'w3tc_flush_all' ),
				static fn() => w3tc_flush_all(),
				static function ( array $urls ) {
					foreach ( $urls as $url ) {
						w3tc_flush_url( $url );
					}
				},
				// The footer is also written on freshly generated pages, but then carries a reason in parentheses
				// ("Page Caching using Disk (Requested URI is rejected)"), so only a bare engine name counts.
				Fingerprint::body( '/Page Caching using [^\r\n(]+?\s*[\r\n]/', 'W3 Total Cache page cache' )
			),
			new CallbackLayer(
				'wp-super-cache',
				'WP Super Cache',
				Tier::PLUGIN,
				static fn() => function_exists( 'wp_cache_clear_cache' ),
				static fn() => wp_cache_clear_cache(),
				static function ( array $urls ) {
					foreach ( $urls as $url ) {
						function_exists( 'wpsc_delete_url_cache' ) ? wpsc_delete_url_cache( $url ) : wp_cache_clear_cache();
					}
				},
				Fingerprint::body( '/Cached page generated by WP-Super-Cache on/', 'WP Super Cache' )
			),
			new CallbackLayer(
				'wp-fastest-cache',
				'WP Fastest Cache',
				Tier::PLUGIN,
				// wpfc_clear_all_cache() is a method of WpFastestCache, not a global function; the action is the public entry point.
				static fn() => class_exists( 'WpFastestCache' ),
				static fn() => do_action( 'wpfc_clear_all_cache', true ),
				null,
				Fingerprint::body( '/WP Fastest Cache file was created in/', 'WP Fastest Cache' )
			),
			new CallbackLayer(
				'nginx-helper',
				'Nginx Helper',
				Tier::PLUGIN,
				static fn() => defined( 'NGINX_HELPER_BASENAME' ),
				static fn() => do_action( 'rt_nginx_helper_purge_all' )
			),
			new CallbackLayer(
				'siteground',
				'SiteGround Optimizer',
				Tier::HOST,
				static fn() => function_exists( 'sg_cachepress_purge_everything' ) || function_exists( 'sg_cachepress_purge_cache' ),
				// sg_cachepress_purge_cache() without a URL only purges the home page.
				static fn() => function_exists( 'sg_cachepress_purge_everything' ) ? sg_cachepress_purge_everything() : sg_cachepress_purge_cache(),
				static function ( array $urls ) {
					foreach ( $urls as $url ) {
						function_exists( 'sg_cachepress_purge_cache' ) ? sg_cachepress_purge_cache( $url ) : sg_cachepress_purge_everything();
					}
				},
				Fingerprint::header( 'x-proxy-cache', '/^HIT$/i', 'SiteGround dynamic cache' )
			),
			new CallbackLayer(
				'wp-engine',
				'WP Engine',
				Tier::HOST,
				static fn() => class_exists( 'WpeCommon' ),
				static function () {
					if ( ! method_exists( 'WpeCommon', 'purge_varnish_cache' ) ) {
						throw new \RuntimeException( 'WpeCommon::purge_varnish_cache() not available' );
					}
					if ( method_exists( 'WpeCommon', 'purge_memcached' ) ) {
						\WpeCommon::purge_memcached();
					}
					\WpeCommon::purge_varnish_cache();
				},
				null,
				Fingerprint::header( 'x-cache', '/^HIT/i', 'WP Engine cache' )
			),
			new CallbackLayer(
				'kinsta',
				'Kinsta',
				Tier::HOST,
				static fn() => class_exists( '\Kinsta\Cache' ),
				static function () {
					global $kinsta_cache;
					if ( ! is_object( $kinsta_cache ) || ! isset( $kinsta_cache->kinsta_cache_purge ) || ! method_exists( $kinsta_cache->kinsta_cache_purge, 'purge_complete_caches' ) ) {
						throw new \RuntimeException( 'Kinsta cache API not available' );
					}
					$kinsta_cache->kinsta_cache_purge->purge_complete_caches();
				},
				null,
				Fingerprint::header( 'x-kinsta-cache', '/^HIT$/i', 'Kinsta cache' )
			),
		);
	}

	/**
	 * Files that page builders and minifiers generate (CSS, JS). They are not tied to one page, so they
	 * are only cleared when everything is purged, and only when the site owner switched this on.
	 *
	 * Autoptimize (`autoptimizeCache::clearall()`, the call its own WP-CLI command makes) and Beaver Builder
	 * (`FLBuilderModel::delete_asset_cache_for_all_posts()`, recommended by its support) were confirmed in
	 * community sources on 2026-11-24. Elementor's `files_manager->clear_cache()` and Divi's
	 * `ET_Core_PageResource::remove_static_resources()` are from memory and public snippets, not from
	 * documentation. Each call is guarded and throws when the method is missing, so a mistake shows as a
	 * failed layer instead of silently doing nothing.
	 *
	 * @param callable(): bool $enabled
	 * @return CallbackLayer[]
	 */
	public static function assetLayers( callable $enabled ): array {
		$layer = static fn( string $id, string $label, callable $installed, callable $clear ) => new CallbackLayer(
			$id,
			$label,
			Tier::PLUGIN,
			static fn() => $enabled() && $installed(),
			$clear,
			null,
			null,
			true
		);
		return array(
			$layer(
				'elementor-files',
				'Elementor CSS files',
				static fn() => class_exists( '\\Elementor\\Plugin' ),
				static function () {
					$plugin = \Elementor\Plugin::$instance ?? null;
					if ( ! is_object( $plugin ) || ! is_object( $plugin->files_manager ?? null ) || ! method_exists( $plugin->files_manager, 'clear_cache' ) ) {
						throw new \RuntimeException( 'This Elementor version has no files_manager->clear_cache().' );
					}
					$plugin->files_manager->clear_cache();
				}
			),
			$layer(
				'divi-static',
				'Divi static CSS',
				static fn() => class_exists( 'ET_Core_PageResource' ),
				static function () {
					if ( ! method_exists( 'ET_Core_PageResource', 'remove_static_resources' ) ) {
						throw new \RuntimeException( 'This Divi version has no ET_Core_PageResource::remove_static_resources().' );
					}
					\ET_Core_PageResource::remove_static_resources( 'all', 'all' );
				}
			),
			$layer(
				'beaver-builder-assets',
				'Beaver Builder assets',
				static fn() => class_exists( 'FLBuilderModel' ),
				static function () {
					if ( ! method_exists( 'FLBuilderModel', 'delete_asset_cache_for_all_posts' ) ) {
						throw new \RuntimeException( 'This Beaver Builder version has no FLBuilderModel::delete_asset_cache_for_all_posts().' );
					}
					\FLBuilderModel::delete_asset_cache_for_all_posts();
				}
			),
			$layer(
				'autoptimize',
				'Autoptimize cache',
				static fn() => class_exists( 'autoptimizeCache' ),
				static function () {
					if ( ! method_exists( 'autoptimizeCache', 'clearall' ) ) {
						throw new \RuntimeException( 'This Autoptimize version has no autoptimizeCache::clearall().' );
					}
					\autoptimizeCache::clearall();
				}
			),
		);
	}
}
