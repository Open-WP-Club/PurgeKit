	/**
	 * Full page-cache purge for WP-Optimize, through the plugin's own object.
	 *
	 * @throws \RuntimeException When the plugin has no page cache to purge.
	 */
	private static function wpOptimizePurge(): void {
		$cache = class_exists( 'WP_Optimize' ) && method_exists( 'WP_Optimize', 'instance' ) ? \WP_Optimize::instance()->get_page_cache() : null;
		if ( ! is_object( $cache ) || ! method_exists( $cache, 'purge' ) ) {
			throw new \RuntimeException( 'This WP-Optimize version has no page cache purge().' );
		}
		$cache->purge();
	}

	/**
	 * Files that page builders and minifiers generate (CSS, JS). They are not tied to one page, so they
	 * are only cleared when everything is purged, and only when the site owner switched this on.
	 *
	 * Autoptimize (`autoptimizeCache::clearall()`, the call its own WP-CLI command makes) and Beaver Builder
	 * (`FLBuilderModel::delete_asset_cache_for_all_posts()`, recommended by its support) were confirmed in
	 * community sources on 2026-11-24. Elementor's `files_manager->clear_cache()` and Divi's
	 * `ET_Core_PageResource::remove_static_resources()` are from memory and public snippets, not from
	 * documentation. Each call is guarded and throws when the method is missing, so a mistake shows as a
	 * failed layer instead of silently doing nothing.
	 *
	 * @param callable(): bool $enabled
	 * @return CallbackLayer[]
	 */
	public static function assetLayers( callable $enabled ): array {
		$layer = static fn( string $id, string $label, callable $installed, callable $clear ) => new CallbackLayer(
			$id,
			$label,
			Tier::PLUGIN,
			static fn() => $enabled() && $installed(),
			$clear,
			null,
			null,
			true
		);
		return array(
			$layer(
				'elementor-files',
				'Elementor CSS files',
				static fn() => class_exists( '\\Elementor\\Plugin' ),
				static function () {
					$plugin = \Elementor\Plugin::$instance ?? null;
					if ( ! is_object( $plugin ) || ! is_object( $plugin->files_manager ?? null ) || ! method_exists( $plugin->files_manager, 'clear_cache' ) ) {
						throw new \RuntimeException( 'This Elementor version has no files_manager->clear_cache().' );
					}
					$plugin->files_manager->clear_cache();
				}
			),
			$layer(
				'divi-static',
				'Divi static CSS',
				static fn() => class_exists( 'ET_Core_PageResource' ),
				static function () {
					if ( ! method_exists( 'ET_Core_PageResource', 'remove_static_resources' ) ) {
						throw new \RuntimeException( 'This Divi version has no ET_Core_PageResource::remove_static_resources().' );
					}
					\ET_Core_PageResource::remove_static_resources( 'all', 'all' );
				}
			),
			$layer(
				'beaver-builder-assets',
				'Beaver Builder assets',
				static fn() => class_exists( 'FLBuilderModel' ),
				static function () {
					if ( ! method_exists( 'FLBuilderModel', 'delete_asset_cache_for_all_posts' ) ) {
						throw new \RuntimeException( 'This Beaver Builder version has no FLBuilderModel::delete_asset_cache_for_all_posts().' );
					}
					\FLBuilderModel::delete_asset_cache_for_all_posts();
				}
			),
			$layer(
				'autoptimize',
				'Autoptimize cache',
				static fn() => class_exists( 'autoptimizeCache' ),
				static function () {
					if ( ! method_exists( 'autoptimizeCache', 'clearall' ) ) {
						throw new \RuntimeException( 'This Autoptimize version has no autoptimizeCache::clearall().' );
					}
					\autoptimizeCache::clearall();
				}
			),
			// Perfmatters documents both calls: https://perfmatters.io/docs/remove-unused-css/ and https://perfmatters.io/docs/minify-css-wordpress/
			// The class names are held in variables so a missing plugin is a plain "not detected", not a fatal error.
			$layer(
				'perfmatters',
				'Perfmatters (used CSS and minified CSS)',
				static fn() => class_exists( 'Perfmatters\\CSS' ) || class_exists( 'Perfmatters\\Minify' ),
				static function () {
					$css      = 'Perfmatters\\CSS';
					$minify   = 'Perfmatters\\Minify';
					$cleared  = false;
					if ( class_exists( $css ) && method_exists( $css, 'clear_used_css' ) ) {
						$css::clear_used_css();
						$cleared = true;
					}
					if ( class_exists( $minify ) && method_exists( $minify, 'clear_minified' ) ) {
						$minify::clear_minified( 'css' );
						$cleared = true;
					}
					if ( ! $cleared ) {
						throw new \RuntimeException( 'This Perfmatters version has neither CSS::clear_used_css() nor Minify::clear_minified().' );
					}
				}
			),
			// Oxygen: only the universal CSS cache. The function is known from a third-party snippet written for Oxygen 3.9 and 4.0;
			// Oxygen's own documentation only describes the "Regenerate CSS Cache" button. Per-post CSS is not touched.
			$layer(
				'oxygen-universal-css',
				'Oxygen universal CSS',
				static fn() => function_exists( 'oxygen_vsb_cache_universal_css' ),
				static function () {
					if ( ! function_exists( 'oxygen_vsb_cache_universal_css' ) || ! oxygen_vsb_cache_universal_css() ) {
						throw new \RuntimeException( 'Oxygen did not regenerate its universal CSS.' );
					}
				}
			),
		);
	}
