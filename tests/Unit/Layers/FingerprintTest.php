<?php
namespace PurgeKit\Tests\Unit\Layers;

use PHPUnit\Framework\TestCase;
use PurgeKit\Layers\Catalog;
use PurgeKit\Layers\CloudflareLayer;
use PurgeKit\Layers\Fingerprint;
use PurgeKit\Layers\VarnishLayer;
use PurgeKit\Secrets\Secrets;
use PurgeKit\Tests\Fakes\FakeHttp;
use PurgeKit\Tests\Fakes\FakeStore;

final class FingerprintTest extends TestCase {
	private function layer( string $id ) {
		foreach ( Catalog::callbackLayers() as $l ) {
			if ( $l->id() === $id ) {
				return $l;
			}
		}
		$this->fail( $id );
	}

	public function test_header_helper_is_case_insensitive_on_value_and_handles_arrays(): void {
		$f = Fingerprint::header( 'x-cache', '/^HIT/i', 'X' );
		$this->assertNotNull( $f( array( 'x-cache' => 'hit from edge' ) ) );
		$this->assertNull( $f( array( 'x-cache' => 'MISS' ) ) );
		$this->assertNull( $f( array() ) );
	}

	public function test_cloudflare_and_varnish_headers(): void {
		$cf = new CloudflareLayer( new FakeHttp(), new Secrets( new FakeStore(), 'k' ), new FakeStore() );
		$this->assertNotNull( $cf->servedFrom( array( 'cf-cache-status' => 'HIT' ) ) );
		$this->assertNull( $cf->servedFrom( array( 'cf-cache-status' => 'DYNAMIC' ) ) );
		$v = new VarnishLayer( new FakeHttp(), new FakeStore(), 'https://a.test' );
		$this->assertNotNull( $v->servedFrom( array( 'x-varnish' => '32770 32771' ) ) );
		$this->assertNull( $v->servedFrom( array( 'x-varnish' => '32770' ) ) );
	}

	public function test_body_signatures(): void {
		$this->assertNotNull( $this->layer( 'wp-rocket' )->servedFrom( array(), '<html></html><!-- Debug: cached@1700000000 -->' ) );
		$this->assertNull( $this->layer( 'wp-rocket' )->servedFrom( array(), '<html></html>' ) );
		$this->assertNotNull( $this->layer( 'wp-super-cache' )->servedFrom( array(), "<!-- Cached page generated by WP-Super-Cache on 2026-01-01 10:00:00 -->" ) );
		$this->assertNull( $this->layer( 'wp-super-cache' )->servedFrom( array(), '<!-- Dynamic page generated in 0.4 seconds. -->' ) );
		$this->assertNotNull( $this->layer( 'wp-fastest-cache' )->servedFrom( array(), '<!-- WP Fastest Cache file was created in 0.2 seconds, on 01-01-26 -->' ) );
	}

	public function test_w3tc_footer_only_counts_without_a_reject_reason(): void {
		$w3 = $this->layer( 'w3tc' );
		$this->assertNotNull( $w3->servedFrom( array(), "<!--\r\nPage Caching using Disk: Enhanced\r\n\r\nServed from: a @ now by W3 Total Cache\r\n-->" ) );
		$this->assertNull( $w3->servedFrom( array(), "<!--\r\nPage Caching using Disk (Requested URI is rejected)\r\n-->" ) );
	}

	public function test_header_fingerprints_in_catalog(): void {
		$this->assertNotNull( $this->layer( 'litespeed' )->servedFrom( array( 'x-litespeed-cache' => 'hit' ) ) );
		$this->assertNotNull( $this->layer( 'kinsta' )->servedFrom( array( 'x-kinsta-cache' => 'HIT' ) ) );
		$this->assertNull( $this->layer( 'kinsta' )->servedFrom( array( 'x-kinsta-cache' => 'MISS' ) ) );
	}
}
